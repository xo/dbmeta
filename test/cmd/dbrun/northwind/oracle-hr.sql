create role northwind_reader
/
begin
  for t in (select owner, object_name from all_objects
            where owner in ('NORTHWIND', 'HR') and object_type in ('TABLE', 'VIEW', 'MATERIALIZED VIEW')) loop
    execute immediate 'grant select on ' || t.owner || '.' || t.object_name || ' to northwind_reader';
  end loop;
end;
