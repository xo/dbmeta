create table departments (
  department_id integer generated always as identity primary key,
  code char(4) not null unique,
  name varchar2(200) not null,
  budget number(14, 2) check (budget >= 0),
  head_count number(5) default 0 not null,
  cost_per_head number(14, 2) generated always as (budget / nullif(head_count, 0)) virtual,
  is_active number(1) default 1 not null check (is_active in (0, 1)),
  tags tag_list,
  settings clob check (settings is json),
  office postal_address,
  network varchar2(45),
  opened_on date,
  review_every interval year to month,
  created_at timestamp with time zone default systimestamp not null,
  updated_at timestamp with time zone
)
/
comment on table departments is 'the departments of the company'
/
comment on column departments.cost_per_head is 'budget divided by head count, null with no one'
/
create index departments_active_idx on departments (case when is_active = 1 then name end)
/
create index departments_lower_name_idx on departments (lower(name))
/
create table staff (
  staff_id raw(16) default sys_guid() primary key,
  employee_id integer references northwind.employees (employee_id),
  department_id integer not null references departments (department_id) on delete cascade,
  email varchar2(254) not null unique
    constraint staff_email_check check (regexp_like(email, '^[^@[:space:]]+@[^@[:space:]]+$')),
  status varchar2(12) default 'active' not null
    constraint staff_status_check check (status in ('active', 'on_leave', 'contractor', 'retired')),
  salary number(19, 4),
  rating binary_float,
  photo blob,
  started_on date,
  ended_on date,
  notes clob
)
/
comment on column staff.email is 'an address with one @'
/
create index staff_department_idx on staff (department_id, status)
/
create table events (
  event_id integer generated by default as identity,
  happened_at timestamp not null,
  kind varchar2(30) not null,
  detail clob check (detail is json),
  primary key (event_id, happened_at)
)
partition by range (happened_at) (
  partition events_2025 values less than (timestamp '2026-01-01 00:00:00'),
  partition events_2026 values less than (timestamp '2027-01-01 00:00:00')
)
/
comment on table events is 'an audit log, one partition for each year'
/
create or replace trigger departments_touch before update on departments
  for each row
begin
  :new.updated_at := systimestamp;
end;
/
create or replace trigger staff_log after insert or update or delete on staff
  for each row
declare
  kind events.kind%type;
begin
  kind := case when inserting then 'insert' when updating then 'update' else 'delete' end;
  insert into events (happened_at, kind, detail)
  values (systimestamp, kind,
    json_object('staff_id' value rawtohex(coalesce(:new.staff_id, :old.staff_id))));
end;
/
create or replace procedure give_raise(department integer, percent number) as
begin
  update staff set salary = salary * (1 + percent / 100) where department_id = department;
end;
/
create or replace function department_size(department integer) return number as
  n number;
begin
  select count(*) into n from staff where department_id = department;
  return n;
end;
/
comment on table staff is 'the people of the company, one row each'
/
create or replace package payroll as
  function total(department integer) return number;
  procedure raise_all(percent number);
end payroll;
/
create or replace package body payroll as
  function total(department integer) return number as
    t number;
  begin
    select nvl(sum(salary), 0) into t from staff where department_id = department;
    return t;
  end;
  procedure raise_all(percent number) as
  begin
    update staff set salary = salary * (1 + percent / 100);
  end;
end payroll;
/
create or replace view active_departments as
  select d.code, d.name, d.budget, department_size(d.department_id) as staff
  from departments d
  where d.is_active = 1
