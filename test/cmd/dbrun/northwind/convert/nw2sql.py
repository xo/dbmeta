"""nw2sql converts the PostgreSQL Northwind script to MySQL, SQLite, DuckDB,
Firebird or SAP HANA.

usage: python3 -I nw2sql.py PRODUCT postgres.sql out.sql tail.sql

PRODUCT is mysql, sqlite3, duckdb, firebird or hana. The script reads the
tables, the indexes, the rows, the keys and the views of the PostgreSQL file,
and leaves its functions out, because the tail file holds the same procedures
written for the product. Each statement of the output ends with a semicolon.
"""
import re
import sys


def split(src):
    """Split at each semicolon outside a quote, a comment or a $$ string."""
    out, buf, i, n = [], [], 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("--", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            buf.append(src[i:j])
            i = j
        elif c == "'":
            j = i + 1
            while j < n:
                if src[j] == "'":
                    if j + 1 < n and src[j + 1] == "'":
                        j += 2
                        continue
                    break
                j += 1
            buf.append(src[i:j + 1])
            i = j + 1
        elif c == "$" and re.match(r"\$\w*\$", src[i:]):
            tag = re.match(r"\$\w*\$", src[i:]).group(0)
            j = src.find(tag, i + len(tag))
            buf.append(src[i:j + len(tag)])
            i = j + len(tag)
        elif c == ";":
            out.append("".join(buf).strip())
            buf = []
            i += 1
        else:
            buf.append(c)
            i += 1
    rest = "".join(buf).strip()
    if rest and not all(l.strip().startswith("--") or not l.strip() for l in rest.split("\n")):
        out.append(rest)
    return [s for s in out if s]


def strip_comments(s):
    return "\n".join(l for l in s.split("\n") if not l.strip().startswith("--"))


# What each product calls a type. The first column that holds money is
# decimal(19,4), which is what Oracle holds (D256), and decimal(18,4) where the
# product stops at 18 digits.
TYPES = {
    "mysql": [(r"\bbytea\b", "longblob"), (r"\bmoney\b", "decimal(19,4)"), (r"\breal\b", "float"),
              (r"\btimestamp\b", "datetime")],
    "sqlite3": [(r"\bbytea\b", "blob"), (r"\bmoney\b", "numeric"), (r"\btimestamp\b", "datetime")],
    "duckdb": [(r"\bbytea\b", "blob"), (r"\bmoney\b", "decimal(19,4)"), (r"\bvarchar\(\d+\)", "varchar")],
    "firebird": [(r"\bbytea\b", "blob sub_type binary"), (r"\btext\b", "blob sub_type text"),
                 (r"\bmoney\b", "decimal(18,4)"), (r"\breal\b", "float")],
    "hana": [(r"\bbytea\b", "blob"), (r"\btext\b", "nclob"), (r"\bmoney\b", "decimal(19,4)"),
             (r"\bvarchar\((\d+)\)", r"nvarchar(\1)"), (r"\bchar\s*\((\d+)\)", r"nvarchar(\1)"),
             (r"\bsmallint\b", "smallint")],
}

IDENTITY = re.compile(r"(\w+) integer generated by default as identity not null")


def table(product, s, identity_seq):
    s = s.replace("0::money", "0")
    s = re.sub(r",\s*constraint\s+ck_birthdate\s+check\s*\(birth_date < now\(\)\)", "", s)
    for a, b in TYPES[product]:
        s = re.sub(a, b, s)
    if product == "mysql":
        s = IDENTITY.sub(r"\1 integer not null auto_increment", s)
    elif product in ("sqlite3",):
        s = IDENTITY.sub(r"\1 integer not null", s)
    elif product == "duckdb":
        name = re.match(r"create table (\w+)", s).group(1)
        s = IDENTITY.sub(lambda m: f"{m.group(1)} integer not null default nextval('{name}_{m.group(1)}_seq')", s)
    # A DEFAULT comes before NULL and NOT NULL in Firebird.
    if product in ("firebird", "hana"):
        s = re.sub(r"\bdefault \((\d+)\)", r"default \1", s)
    if product == "firebird":
        s = re.sub(r"\b(not null|null) default (\d+)", r"default \2 \1", s)
        s = re.sub(r"(?<!not )\bnull\b", "", s)
    return s


def hexliteral(product, h):
    if product in ("mysql", "sqlite3"):
        return "x'" + h + "'"
    if product == "duckdb":
        return "unhex('" + h + "')"
    if product == "firebird":
        chunks = [h[p:p + 16000] for p in range(0, len(h), 16000)] or [""]
        return " || ".join("cast(x'" + c + "' as blob sub_type binary)" for c in chunks)
    if product == "hana":
        return "to_blob(hextobin('" + h + "'))"
    raise SystemExit("no binary literal for " + product)


def insert(product, s):
    return re.sub(r"'\\x([0-9A-Fa-f]*)'(?:::bytea)?", lambda m: hexliteral(product, m.group(1)), s)


EXT = "order_details.unit_price*quantity*((1-discount)::real)"


def view(product, s):
    s = strip_comments(s)
    if product in ("duckdb", "hana"):
        # discount is a float, and these keep single precision through the
        # sum unless the cents are a decimal.
        s = s.replace(EXT, "cast(round(order_details.unit_price*quantity*(1-cast(discount as double)), 2) as decimal(19,2))")
    else:
        s = s.replace(EXT, "round(order_details.unit_price*quantity*(1-discount), 2)")
    if product == "sqlite3":
        # SQLite adds doubles, so a sum of cents needs its own rounding.
        r = "round(order_details.unit_price*quantity*(1-discount), 2)"
        s = s.replace("sum((" + r + "))", "round(sum(" + r + "), 2)")
    s = s.replace("2500::money", "2500")
    s = re.sub(r"'(\d{4})(\d{2})(\d{2})'", r"'\1-\2-\3'", s)
    s = re.sub(r"avg\(unit_price::numeric\)::money", "avg(unit_price)", s)
    if product == "mysql":
        s = s.replace("(first_name || ' ' || last_name)", "concat(first_name, ' ', last_name)")
    return s


def items(s):
    """Return the top level items of the first VALUES list of an insert."""
    i = s.upper().index("VALUES")
    j = s.index("(", i)
    out, depth, k, start = [], 0, j + 1, j + 1
    while k < len(s):
        c = s[k]
        if c == "'":
            k += 1
            while True:
                if s[k] == "'":
                    if s[k + 1] == "'":
                        k += 2
                        continue
                    break
                k += 1
        elif c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                out.append(s[start:k].strip())
                return out
            depth -= 1
        elif c == "," and depth == 0:
            out.append(s[start:k].strip())
            start = k + 1
        k += 1
    raise ValueError("no end of VALUES")


def parents_first(rows, parent_index):
    """Order the inserts of a table that refers to itself, so that the row a
    row refers to comes before it. The first item is the key."""
    parsed = [(items(r), r) for r in rows]
    key = {p[0][0]: p for p in parsed}
    out, done = [], set()

    def visit(p):
        k = p[0][0]
        if k in done:
            return
        done.add(k)
        parent = p[0][parent_index]
        if parent != "NULL" and parent in key:
            visit(key[parent])
        out.append(p[1])

    for p in parsed:
        visit(p)
    return out


def fk_and_pk(s):
    m = re.match(r"alter table (\w+)\s+add constraint (\w+)\s+(primary key|foreign key)\s*\(([^)]*)\)(?:\s+references (\w+)\s*\(([^)]*)\))?", s, re.I | re.S)
    return m


def main():
    product, src, dst, tail = sys.argv[1:5]
    inline = product in ("sqlite3", "duckdb")
    statements = split(open(src).read())
    tables, order, indexes, inserts, views, alters, identity = {}, [], [], [], [], [], {}
    out = []
    for st in statements:
        st = re.sub(r"\A(?:\s*--[^\n]*\n)+", "", st).strip()
        low = st.lower()
        if low.startswith("create table"):
            name = re.match(r"create table (\w+)", low).group(1)
            tables[name] = st
            order.append(name)
            m = IDENTITY.search(st)
            if m:
                identity[name] = m.group(1)
        elif low.startswith("create index"):
            indexes.append(st)
        elif low.startswith("insert into"):
            inserts.append(st)
        elif low.startswith("alter table"):
            alters.append(st)
        elif low.startswith("create view"):
            views.append(view(product, st))
        elif low.startswith("select setval") or low.startswith("create function") or low.startswith("--") or not low:
            continue
        else:
            raise SystemExit("an unknown statement: " + st[:60])
    maxes = {}
    for st in inserts:
        m = re.match(r"insert into (\w+).*?values\s*\((\d+)", st, re.I | re.S)
        if m and m.group(1) in identity:
            maxes[m.group(1)] = max(maxes.get(m.group(1), 0), int(m.group(2)))
    if inline:
        # SQLite and DuckDB take a key only in CREATE TABLE, so the keys of the
        # ALTER statements move into it, and the tables go in the order of their
        # references.
        extra = {}
        refs = {n: set() for n in tables}
        for st in alters:
            m = fk_and_pk(st)
            if not m:
                raise SystemExit("an unknown alter: " + st[:60])
            t, cname, kind, cols, rt, rcols = m.groups()
            clause = f"constraint {cname} {kind} ({cols.strip()})"
            if rt:
                clause += f" references {rt} ({rcols.strip()})"
                if rt != t:
                    refs[t].add(rt)
            extra.setdefault(t, []).append(clause)
        sorted_names = []
        seen = set()

        def visit(n):
            if n in seen:
                return
            seen.add(n)
            for r in sorted(refs[n]):
                visit(r)
            sorted_names.append(n)

        for n in order:
            visit(n)
        if product == "duckdb":
            for t, col in identity.items():
                out.append(f"create sequence {t}_{col}_seq start with {maxes.get(t, 0) + 1}")
        for n in sorted_names:
            body = table(product, tables[n], identity)
            if n in extra:
                i = body.rindex(")")
                body = body[:i].rstrip() + ",\n\t" + ",\n\t".join(extra[n]) + "\n)"
            out.append(body)
        pos = {n: k for k, n in enumerate(sorted_names)}
        inserts.sort(key=lambda st: pos[re.match(r"insert into (\w+)", st, re.I).group(1)])
        for n in sorted_names:
            if n in extra and any(f"references {n} (" in c for c in extra[n]):
                mine = [st for st in inserts if re.match(r"insert into (\w+)", st, re.I).group(1) == n]
                cols = [c.strip() for c in re.search(r"\(([^)]*)\)\s*VALUES", mine[0], re.I).group(1).split(",")]
                ordered = parents_first(mine, cols.index("reports_to"))
                at = inserts.index(mine[0])
                inserts[at:at + len(mine)] = ordered
        for st in inserts:
            out.append(insert(product, st))
        out.extend(indexes)
        out.extend(views)
    else:
        for n in order:
            body = table(product, tables[n], identity)
            if product == "hana" and n in identity:
                body = body.replace(
                    f"{identity[n]} integer generated by default as identity not null",
                    f"{identity[n]} integer generated by default as identity (start with {maxes.get(n, 0) + 1}) not null")
            out.append(body)
        for st in inserts:
            out.append(insert(product, st))
        if product == "hana":
            # HANA refuses a second index on the same list of columns, and a key is one.
            indexed = set()
            for n in order:
                for cols in re.findall(r"primary key \(([^)]*)\)", tables[n].lower()):
                    indexed.add((n, re.sub(r"\s", "", cols)))
            for st in alters:
                m = re.match(r"alter table (\w+)\s+add constraint \w+\s+(primary key|foreign key)\s*\(([^)]*)\)", st, re.I | re.S)
                if m and m.group(2).lower() == "primary key":
                    indexed.add((m.group(1).lower(), re.sub(r"\s", "", m.group(3).lower())))
            kept = []
            for st in indexes:
                m = re.match(r"create index \w+ on (\w+) \(([^)]*)\)", st.lower())
                key = (m.group(1), re.sub(r"\s", "", m.group(2)))
                if key in indexed:
                    continue
                indexed.add(key)
                kept.append(st)
            indexes = kept
        out.extend(indexes)
        for st in alters:
            out.append(table(product, st, identity))
        out.extend(views)
        if product == "firebird":
            for t, col in identity.items():
                out.append(f"alter table {t} alter column {col} restart with {maxes.get(t, 0) + 1}")
    text = f"-- Northwind for {product}, converted from the PostgreSQL script.\n"
    text += ";\n".join(out) + ";\n"
    text += open(tail).read().rstrip("\n") + "\n"
    open(dst, "w").write(text)


main()
