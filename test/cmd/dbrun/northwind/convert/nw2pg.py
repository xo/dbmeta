"""nw2pg converts Microsoft's T-SQL Northwind script to PostgreSQL.

usage: python3 -I nw2pg.py northwind.sql out.sql
"""
import re
import sys

TYPES = {
    "nvarchar": "varchar", "nchar": "char", "ntext": "text", "image": "bytea",
    "datetime": "timestamp", "money": "money", "smallint": "smallint",
    "bit": "smallint", "real": "real", "integer": "integer", "int": "integer",
}


def snake(word):
    w = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", word)
    return re.sub(r"[\s_]+", "_", w).lower()


def names(sql):
    """names converts each identifier outside strings and comments."""
    out, i, n = [], 0, len(sql)
    while i < n:
        c = sql[i]
        if c == "'":
            j = i + 1
            while j < n:
                if sql[j] == "'" and j + 1 < n and sql[j + 1] == "'":
                    j += 2
                    continue
                if sql[j] == "'":
                    break
                j += 1
            out.append(sql[i:j + 1])
            i = j + 1
        elif sql.startswith("--", i):
            j = sql.find("\n", i)
            j = n if j == -1 else j
            out.append(sql[i:j])
            i = j
        elif sql.startswith("/*", i):
            j = sql.find("*/", i) + 2
            out.append(sql[i:j])
            i = j
        elif c == "[":
            j = sql.index("]", i)
            out.append(snake(sql[i + 1:j]))
            i = j + 1
        elif c.isalpha() or c == "_":
            j = i
            while j < n and (sql[j].isalnum() or sql[j] == "_"):
                j += 1
            out.append(snake(sql[i:j]))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def date(m):
    mo, d, y = m.group(1), m.group(2), m.group(3)
    return f"'{y}-{int(mo):02d}-{int(d):02d}'"


def values(s):
    s = re.sub(r"(?<![A-Za-z0-9'])N'", "'", s)
    s = re.sub(r"'(\d{1,2})/(\d{1,2})/(\d{4})'", date, s)
    s = re.sub(r"\b0x([0-9A-Fa-f]+)", lambda m: f"'\\x{m.group(1)}'::bytea", s)
    return s


def table(s):
    s = names(s)
    s = re.sub(r"\binteger identity \(1, 1\)", "integer generated by default as identity", s)
    s = re.sub(r"\b(nvarchar|nchar|ntext|image|datetime|money|smallint|bit|real)\b",
               lambda m: TYPES[m.group(1)], s)
    s = re.sub(r"\bconstraint \w+ default\b", "default", s)
    s = re.sub(r"\s+(non)?clustered\b", "", s)
    s = re.sub(r"\bgetdate\(\)", "now()", s)
    s = re.sub(r"\s+on primary\b", "", s)
    s = re.sub(r"\((\w*(price|freight)\w*) >= 0\)", r"(\1 >= 0::money)", s)
    return keys(s)


def view(s):
    s = names(s)
    s = re.sub(r"convert\(money,", "cast(", s)
    # The T-SQL script divides by 100 and multiplies by 100 to round a price to
    # cents. A money value of PostgreSQL has cents only, so the division loses
    # the rest, and the product of a price, a quantity and a discount is already
    # money rounded to cents.
    # SQL Server subtracts the discount in single precision, and PostgreSQL
    # would do it in double precision, so the cast brings the result back to a
    # real, which gives the same cents.
    s = re.sub(r"cast\(\((.*?)/100\)\)\*100", r"(\1)", s)
    s = s.replace("*(1-discount)", "*((1-discount)::real)")
    s = s.replace("(first_name + ' ' + last_name)", "(first_name || ' ' || last_name)")
    # money has no avg, and compares only with money
    s = s.replace("avg(unit_price)", "avg(unit_price::numeric)::money")
    s = s.replace("subtotal >2500", "subtotal > 2500::money")
    return s


indexes = set()
foreign = []


def keys(s):
    """keys moves the foreign keys of a table to the end, after the rows."""
    m = re.match(r"create table (\w+)", s)
    if not m:
        return s
    kept = []
    for line in s.split("\n"):
        k = re.match(r"\s*(constraint \w+ foreign key .*?),?$", line)
        if k:
            foreign.append(f"alter table {m.group(1)} add {k.group(1)}")
        else:
            kept.append(line)
    # a comma may now end the last column
    return re.sub(r",(\s*\n\))", r"\1", "\n".join(kept))


def index(s):
    m = re.match(r"CREATE INDEX \[(\w+)\] ON \[?(\w+)\]? \((.*)\)", s.strip())
    name, tbl, cols = snake(m.group(1)), snake(m.group(2)), names(m.group(3))
    idx = f"{tbl}_{name}_idx"
    if idx in indexes:
        return None
    indexes.add(idx)
    return f"create index {idx} on {tbl} ({cols})"


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    src = src.replace("[ShipCountry]);\nVALUES", "[ShipCountry])\nVALUES")
    # an insert with no ; before the next one
    src = re.sub(r"\)\n(INSERT INTO)", r");\n\1", src)
    out = []
    for stmt in re.split(r";[ \t]*\n", src):
        s = re.sub(r"^(\s*/\*.*?\*/\s*)+", "", stmt.strip(), flags=re.S).strip()
        if not s:
            continue
        head = s.split(None, 2)
        word = " ".join(head[:2]).upper()
        if word.startswith("SET ") or "CHECK CONSTRAINT ALL" in s.upper() or word == "CREATE PROCEDURE":
            continue
        if word == "CREATE TABLE":
            out.append(table(s))
        elif word == "CREATE INDEX":
            s = index(s)
            if s is None:
                continue
            out.append(s)
        elif word == "CREATE VIEW":
            out.append(view(s))
        elif word.startswith("INSERT"):
            s = re.sub(r"^INSERT (?!INTO)", "INSERT INTO ", s)
            # the names come before VALUES, the values after it
            k = s.upper().index("VALUES")
            out.append(names(s[:k]) + values(s[k:]))
        elif word.startswith("ALTER TABLE"):
            out.append(table(s))
        else:
            raise SystemExit(f"unknown statement: {s[:80]!r}")
    out.extend(foreign)
    out.append(open(sys.argv[3]).read() if len(sys.argv) > 3 else "")
    # a statement can end in a comment line, so the ; goes on a line of its own
    text = "\n;\n".join(x.rstrip() for x in out if x.strip())
    head = "-- Northwind for PostgreSQL, converted from Microsoft's T-SQL script.\n"
    open(sys.argv[2], "w", encoding="utf-8").write(head + text + ";\n")


main()
