-- Objects that Northwind lacks, for the describe commands of usql.

create extension if not exists pg_trgm;
create extension if not exists citext;

create schema hr;
comment on schema hr is 'people, departments and what happens to them';

create type hr.employment_status as enum ('active', 'on_leave', 'contractor', 'retired');
create domain hr.email as citext check (value ~ '^[^@\s]+@[^@\s]+$');
comment on domain hr.email is 'an address with one @';
create type hr.postal_address as (street text, city text, postal_code text, country text);

create sequence hr.ticket_seq start 1000 increment 10;

create table hr.departments (
  department_id integer generated always as identity primary key,
  code char(4) not null unique,
  name text not null,
  budget numeric(14, 2) check (budget >= 0),
  head_count smallint not null default 0,
  cost_per_head numeric(14, 2) generated always as (budget / nullif(head_count, 0)) stored,
  is_active boolean not null default true,
  tags text[] not null default '{}',
  settings jsonb,
  office hr.postal_address,
  network inet,
  opened_on date,
  review_every interval,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);
comment on table hr.departments is 'the departments of the company';
comment on column hr.departments.cost_per_head is 'budget divided by head count, null with no one';
create index departments_active_idx on hr.departments (name) where is_active;
create index departments_lower_name_idx on hr.departments (lower(name));
create index departments_settings_idx on hr.departments using gin (settings);

create table hr.staff (
  staff_id uuid primary key default gen_random_uuid(),
  employee_id integer references public.employees (employee_id),
  department_id integer not null references hr.departments (department_id) on delete cascade,
  email hr.email not null unique,
  status hr.employment_status not null default 'active',
  salary money,
  rating real,
  photo bytea,
  started timestamp(0),
  ended timestamp(0),
  notes text
);
create index staff_department_idx on hr.staff (department_id, status);

create table hr.events (
  event_id bigint generated by default as identity,
  happened_at timestamptz not null,
  kind text not null,
  detail jsonb,
  primary key (event_id, happened_at)
) partition by range (happened_at);
create table hr.events_2025 partition of hr.events for values from ('2025-01-01') to ('2026-01-01');
create table hr.events_2026 partition of hr.events for values from ('2026-01-01') to ('2027-01-01');
comment on table hr.events is 'an audit log, one partition for each year';

create function hr.touch_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end
$$;
create trigger departments_touch before update on hr.departments
  for each row execute function hr.touch_updated_at();

create function hr.log_staff_change() returns trigger language plpgsql as $$
begin
  insert into hr.events (happened_at, kind, detail)
  values (now(), lower(tg_op), jsonb_build_object('staff_id', coalesce(new.staff_id, old.staff_id)));
  return null;
end
$$;
create trigger staff_log after insert or update or delete on hr.staff
  for each row execute function hr.log_staff_change();

create procedure hr.give_raise(department integer, percent numeric)
language plpgsql as $$
begin
  update hr.staff set salary = salary * (1 + percent / 100) where department_id = department;
end
$$;

create function hr.department_size(department integer) returns bigint
language sql stable as $$ select count(*) from hr.staff where department_id = department $$;
comment on function hr.department_size(integer) is 'the number of staff in a department';

create aggregate hr.concat_lines(text) (sfunc = textcat, stype = text, initcond = '');

create view hr.active_departments as
  select d.code, d.name, d.budget, hr.department_size(d.department_id) as staff
  from hr.departments d
  where d.is_active;

create materialized view public.sales_by_country as
  select c.country, count(distinct o.order_id) as orders,
    sum(od.unit_price * od.quantity * (1 - od.discount)) as sales
  from customers c
    join orders o on o.customer_id = c.customer_id
    join order_details od on od.order_id = o.order_id
  group by c.country
with data;
create unique index sales_by_country_country_idx on public.sales_by_country (country);
create index products_name_trgm_idx on public.products using gin (product_name gin_trgm_ops);

