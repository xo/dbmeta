func TestParseTypeReadsTheDeclaredTypesOfOracle(t *testing.T) {
	t.Parallel()
	for _, c := range []struct {
		text string
		want dump.Type
	}{
		{"VARCHAR2(200 CHAR)", dump.Type{Kind: dump.String, Length: 200}},
		{"CHAR(4)", dump.Type{Kind: dump.String, Fixed: true, Length: 4}},
		{"NUMBER(14,2)", dump.Type{Kind: dump.Decimal, Precision: 14, Scale: 2}},
		{"NUMBER(5)", dump.Type{Kind: dump.Integer, Bits: 32}},
		{"NUMBER(*,0)", dump.Type{Kind: dump.BigInteger}},
		{"NUMBER", dump.Type{Kind: dump.Decimal}},
		{"BINARY_FLOAT", dump.Type{Kind: dump.Float, Bits: 32}},
		{"DATE", dump.Type{Kind: dump.LocalTimestamp}},
		{"TIMESTAMP(3)", dump.Type{Kind: dump.LocalTimestamp, Precision: 3}},
		{"TIMESTAMP(6) WITH TIME ZONE", dump.Type{Kind: dump.Timestamp, Precision: 6}},
		{"INTERVAL YEAR(2) TO MONTH", dump.Type{Kind: dump.Interval}},
		{"RAW(16)", dump.Type{Kind: dump.Binary, Length: 16}},
		{"BLOB", dump.Type{Kind: dump.Binary}},
		{"CLOB", dump.Type{Kind: dump.String}},
		{`"HR"."POSTAL_ADDRESS"`, dump.Type{Kind: dump.Other}},
	} {
		got, err := parseType(c.text)
		if err != nil || got.Kind != c.want.Kind || got.Length != c.want.Length || got.Fixed != c.want.Fixed ||
			got.Precision != c.want.Precision || got.Scale != c.want.Scale || got.Bits != c.want.Bits {
			t.Errorf("parseType(%q) = %+v, %v, want %+v", c.text, got, err, c.want)
		}
	}
}

func TestStringLiteralsHoldWhatOracleHolds(t *testing.T) {
	t.Parallel()
	if got, want := literal("it's"), "'it''s'"; got != want {
		t.Errorf("literal = %s, want %s", got, want)
	}
	long := literal(strings.Repeat("é", 3000))
	if !strings.HasPrefix(long, "TO_CLOB('") || !strings.Contains(long, "') || TO_CLOB('") {
		t.Errorf("a text of 6000 bytes is not joined as a CLOB: %.60s", long)
	}
	if got, want := binary("00ff"), "HEXTORAW('00ff')"; got != want {
		t.Errorf("binary = %s, want %s", got, want)
	}
	declare, fill, ref := longBinary(1, strings.Repeat("ab", 20000))
	if declare != "b1 BLOB;" || ref != "b1" || len(fill) != 3 {
		t.Errorf("longBinary = %q, %d statements, %q", declare, len(fill), ref)
	}
}

func TestAnIdentityColumnLoadsAsByDefaultAndIsGivenBackItsKind(t *testing.T) {
	t.Parallel()
	c := dump.Column{Name: "ID", Identity: "always"}
	q := quoteIdentifier
	if got, want := column(c, "NUMBER(*,0)", q, literal), `"ID" NUMBER(*,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL`; got != want {
		t.Errorf("column = %s, want %s", got, want)
	}
	if got, want := identityAfter(`"HR"."T"`, `"ID"`, c), `ALTER TABLE "HR"."T" MODIFY ("ID" GENERATED ALWAYS AS IDENTITY (START WITH LIMIT VALUE))`; got != want {
		t.Errorf("identityAfter = %s, want %s", got, want)
	}
	expr := "BUDGET / 2"
	v := dump.Column{Name: "HALF", Generated: "virtual", Default: &expr, Nullable: true}
	if got, want := column(v, "NUMBER(14,2)", q, literal), `"HALF" NUMBER(14,2) GENERATED ALWAYS AS (BUDGET / 2) VIRTUAL`; got != want {
		t.Errorf("column = %s, want %s", got, want)
	}
}

func TestOnlyTheEndOfABlockKeepsItsSemicolon(t *testing.T) {
	t.Parallel()
	for text, want := range map[string]bool{
		"CREATE OR REPLACE PROCEDURE p AS BEGIN NULL; END;":     true,
		"CREATE OR REPLACE PACKAGE BODY pay AS\nEND pay;":       true,
		"CREATE OR REPLACE TYPE t AS VARRAY(10) OF VARCHAR2(4)": false,
		"CREATE OR REPLACE TYPE t AS OBJECT (a NUMBER);":        false,
	} {
		if got := keepTerminator(text); got != want {
			t.Errorf("keepTerminator(%q) = %v, want %v", text, got, want)
		}
	}
}

func TestAnObjectColumnIsReadAsTheTextOfItsConstructor(t *testing.T) {
	t.Parallel()
	snap := &dump.Snapshot{Schemas: []dump.Schema{{
		Name: "HR",
		Composites: []dump.Composite{{Name: "POSTAL_ADDRESS", Columns: []dump.Column{
			{Name: "STREET", Type: dump.Type{Kind: dump.String, Raw: "VARCHAR2(100)"}},
			{Name: "ZIP", Type: dump.Type{Kind: dump.Decimal, Raw: "NUMBER(5)"}},
		}}},
		Collections: []dump.Collection{{Name: "TAG_LIST", Element: "VARCHAR2"}},
	}}}
	obj := dump.Column{Name: "OFFICE", Type: dump.Type{Kind: dump.Other, Raw: `"HR"."POSTAL_ADDRESS"`}}
	got, ok := selectColumn(snap, "HR", obj, `t."OFFICE"`)
	if !ok || !strings.Contains(got, `'"HR"."POSTAL_ADDRESS"(' ||`) || !strings.Contains(got, `t."OFFICE"."STREET"`) ||
		!strings.Contains(got, `REPLACE(t."OFFICE"."STREET"`) {
		t.Errorf("an object column is read as %s", got)
	}
	tags := dump.Column{Name: "TAGS", Type: dump.Type{Kind: dump.Other, Raw: `"HR"."TAG_LIST"`}}
	got, ok = selectColumn(snap, "HR", tags, `t."TAGS"`)
	if !ok || !strings.Contains(got, `XMLAGG(`) || !strings.Contains(got, `TABLE(t."TAGS")`) {
		t.Errorf("a collection column is read as %s", got)
	}
	if _, ok := selectColumn(snap, "HR", dump.Column{Name: "N", Type: dump.Type{Kind: dump.String, Raw: "VARCHAR2(4)"}}, `t."N"`); ok {
		t.Error("a column of a type of Oracle needs no expression")
	}
}

func TestAnOracleTableWithARefColumnHasANoteAboutItsValues(t *testing.T) {
	t.Parallel()
	typ := dump.Type{Kind: dump.Other, Raw: `REF "HR"."ADDRESS_T"`}
	snap := &dump.Snapshot{
		Version: dump.SnapshotVersion, Dialect: "oracle",
		Schemas: []dump.Schema{{Name: "HR", Tables: []dump.Table{{
			Name: "CONTACTS", Columns: []dump.Column{{Name: "HOME", Type: typ, Nullable: true}},
		}}}},
	}
	var note string
	for st, err := range dump.Script(snap, dbmeta.Oracle, dump.Policy{}) {
		if err != nil {
			t.Fatalf("writing the script: %v", err)
		}
		if st.Kind == "table" {
			note = st.Note
		}
	}
	if !strings.Contains(note, "no value of HOME") {
		t.Errorf("the note of the table is %q", note)
	}
}
